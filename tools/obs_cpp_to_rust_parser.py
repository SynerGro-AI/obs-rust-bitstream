#!/usr/bin/env python3
"""
OBS C/C++ to Rust parser — learned-lessons edition.

Loads tools/lessons.json and emits Rust skeletons that already
apply the known safe patterns and document the fixes.

Usage:
    python3 obs_cpp_to_rust_parser.py path/to/file.c [output.rs]

The parser notes which lessons were applied so future runs can
record additional fixes.
"""

import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

LESSONS_PATH = Path(__file__).parent / "lessons.json"

def load_lessons() -> Dict:
    if LESSONS_PATH.exists():
        with open(LESSONS_PATH) as f:
            return json.load(f)
    return {}

def match_lessons(name: str, source: str, lessons: Dict) -> List[str]:
    """Return list of lesson keys that match this item."""
    text = (name + " " + source).lower()
    matched = []
    for key, lesson in lessons.items():
        for m in lesson.get("match", []):
            if m.lower() in text:
                matched.append(key)
                break
    return matched

def generate(content: str, source: str, lessons: Dict) -> str:
    structs = []
    # Simple struct extraction (tree-sitter upgrade can come later)
    pattern = re.compile(r"struct\s+(\w+)\s*\{([^}]+)\}", re.DOTALL)
    for m in pattern.finditer(content):
        name = m.group(1)
        fields = []
        for line in m.group(2).splitlines():
            line = line.strip().rstrip(";")
            if line and not line.startswith(("//", "/*")):
                parts = line.split()
                if len(parts) >= 2:
                    fields.append(" ".join(parts))
        structs.append({"name": name, "fields": fields})

    lines = [
        "// Generated by obs_cpp_to_rust_parser.py (learned-lessons edition)",
        f"// Source: {source}",
        "// Lessons applied below. Reuse the foundation modules; do not re-implement the bugs.",
        "",
        "use crate::diff::assert_equal; // differential harness",
        "",
    ]

    applied = set()
    for s in structs:
        name = s["name"]
        keys = match_lessons(name, source, lessons)
        lines.append(f"// === struct {name} ===")
        if keys:
            for k in keys:
                lesson = lessons[k]
                lines.append(f"// Lesson [{k}]: {lesson['issue']}")
                lines.append(f"// Fix: {lesson['fix']}")
                lines.append(f"// See: {lesson['module']}")
                lines.append(f"// Hint: {lesson['hint']}")
                applied.add(k)
        else:
            lines.append("// No specific lesson matched. Apply general pattern:")
            lines.append("// safe core + thin C ABI shim + differential test that proves the quirk.")
        lines.append("")

    if not structs:
        lines.append("// No structs. Scan for known function patterns (dstr_, bitstream_, os_get_path_extension, bmalloc).")
        # Also match on whole file
        keys = match_lessons("", source, lessons)
        for k in keys:
            lesson = lessons[k]
            lines.append(f"// File-level lesson [{k}]: {lesson['issue']} → {lesson['fix']}")
            applied.add(k)

    lines.append("")
    lines.append("// --- Applied lessons ---")
    if applied:
        for k in sorted(applied):
            lines.append(f"// - {k}: {lessons[k]['issue']}")
    else:
        lines.append("// (none — consider adding a new lesson to tools/lessons.json)")

    lines.append("")
    lines.append("// Next: cargo test, then wire differential, then optimize.")
    lines.append("// For complex cases feed the skeleton to the AI scaffold (src/ai.rs) for review.")
    return "\n".join(lines)

def note_lesson(key: str, issue: str, fix: str, module: str, hint: str, matches: List[str]):
    """Append a new lesson (called manually or by future automation)."""
    lessons = load_lessons()
    lessons[key] = {
        "match": matches,
        "issue": issue,
        "fix": fix,
        "module": module,
        "hint": hint,
    }
    with open(LESSONS_PATH, "w") as f:
        json.dump(lessons, f, indent=2)
    print(f"Noted lesson: {key}")

def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    path = Path(sys.argv[1])
    if not path.exists():
        print(f"File not found: {path}")
        sys.exit(1)
    content = path.read_text(errors="ignore")
    lessons = load_lessons()
    rust = generate(content, path.name, lessons)
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else path.with_suffix(".rs")
    out.write_text(rust)
    print(f"Wrote {out}")
    print(f"Lessons file: {LESSONS_PATH}")

if __name__ == "__main__":
    main()
