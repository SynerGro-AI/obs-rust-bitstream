//! Physical data for all 118 elements, plus their place in the standard
//! 18-column periodic table.
//!
//! Source: PubChem Periodic Table (National Center for Biotechnology
//! Information, NIH), https://pubchem.ncbi.nlm.nih.gov/periodic-table/ ,
//! downloaded 2026-10-20 from
//! https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/CSV (public domain).
//! Units: mass u (g/mol), radius pm (van der Waals), ionization energy and
//! electron affinity eV, melting/boiling point K, density g/cm³ (gases at
//! STP). Pauling electronegativity. `None` = PubChem has no value (mostly
//! superheavy elements whose bulk properties have never been measured).
//! Some values for synthetic elements are predictions, as in the source.
//!
//! Layout: `col` 1..=18, `row` 1..=7 for the main table; lanthanides
//! (57–71) sit in display row 9 and actinides (89–103) in row 10, columns
//! 3..=17. `group` is `None` for those f-block rows.
//!
//! Generated from the CSV; do not edit by hand.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Category {
    AlkaliMetal,
    AlkalineEarthMetal,
    TransitionMetal,
    PostTransitionMetal,
    Metalloid,
    Nonmetal,
    Halogen,
    NobleGas,
    Lanthanide,
    Actinide,
}

impl Category {
    pub const ALL: [Category; 10] = [
        Category::AlkaliMetal,
        Category::AlkalineEarthMetal,
        Category::TransitionMetal,
        Category::PostTransitionMetal,
        Category::Metalloid,
        Category::Nonmetal,
        Category::Halogen,
        Category::NobleGas,
        Category::Lanthanide,
        Category::Actinide,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Category::AlkaliMetal => "Alkali metal",
            Category::AlkalineEarthMetal => "Alkaline earth metal",
            Category::TransitionMetal => "Transition metal",
            Category::PostTransitionMetal => "Post-transition metal",
            Category::Metalloid => "Metalloid",
            Category::Nonmetal => "Nonmetal",
            Category::Halogen => "Halogen",
            Category::NobleGas => "Noble gas",
            Category::Lanthanide => "Lanthanide",
            Category::Actinide => "Actinide",
        }
    }

    /// Metallic bonding in the elemental solid.
    pub fn is_metal(self) -> bool {
        matches!(
            self,
            Category::AlkaliMetal
                | Category::AlkalineEarthMetal
                | Category::TransitionMetal
                | Category::PostTransitionMetal
                | Category::Lanthanide
                | Category::Actinide
        )
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ElementData {
    pub z: u32,
    pub symbol: &'static str,
    pub name: &'static str,
    /// Standard atomic weight (u).
    pub mass: f32,
    pub category: Category,
    pub col: u8,
    pub row: u8,
    pub period: u8,
    pub group: Option<u8>,
    pub block: char,
    pub config: &'static str,
    pub electronegativity: Option<f32>,
    pub radius_pm: Option<f32>,
    pub ionization_ev: Option<f32>,
    pub electron_affinity_ev: Option<f32>,
    pub oxidation: &'static str,
    pub state: &'static str,
    pub melting_k: Option<f32>,
    pub boiling_k: Option<f32>,
    /// g/cm³
    pub density: Option<f32>,
    /// Conventional CPK/Jmol display colour (0xRRGGBB).
    pub cpk: Option<u32>,
    pub discovered: &'static str,
}

pub fn all() -> &'static [ElementData] {
    ELEMENTS
}

pub fn get(z: u32) -> Option<&'static ElementData> {
    z.checked_sub(1)
        .and_then(|i| ELEMENTS.get(i as usize))
        .filter(|e| e.z == z)
}

/// Symbol (case-insensitive), name (case-insensitive, "aluminium" accepted) or atomic number.
pub fn find(q: &str) -> Option<&'static ElementData> {
    let q = q.trim();
    if let Ok(z) = q.parse::<u32>() {
        return get(z);
    }
    let l = q.to_lowercase();
    let l = match l.as_str() {
        "aluminium" => "aluminum".to_string(),
        "caesium" => "cesium".to_string(),
        "sulphur" => "sulfur".to_string(),
        _ => l,
    };
    ELEMENTS
        .iter()
        .find(|e| e.symbol.eq_ignore_ascii_case(q))
        .or_else(|| ELEMENTS.iter().find(|e| e.name.to_lowercase() == l))
}

/// Exact-case symbol lookup (for formula parsing: "Co" vs "CO").
pub fn by_symbol(sym: &str) -> Option<&'static ElementData> {
    ELEMENTS.iter().find(|e| e.symbol == sym)
}

