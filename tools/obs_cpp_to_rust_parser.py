#!/usr/bin/env python3
"""
OBS C/C++ to Rust parser/generator — work smarter version.

Recognizes known patterns and emits skeletons that point at the
already-perfect foundation modules in this crate:

- bitstream_reader → Position trait (see src/bitstream.rs)
- dstr → safe replace/insert (see src/dstr.rs)
- utf8 truncation → truncate_utf8 (see src/utf8.rs)

Usage:
    python3 obs_cpp_to_rust_parser.py path/to/file.c [output.rs]
"""

import re
import sys
from pathlib import Path
from typing import List, Dict

KNOWN_PATTERNS = {
    "bitstream_reader": "Use the Position trait from this crate (src/bitstream.rs). Wrap vs no-wrap is type-level.",
    "dstr": "Use the safe Dstr from this crate (src/dstr.rs). Empty find is a no-op; no overflow.",
    "utf8": "Use truncate_utf8 / truncate_filename from this crate (src/utf8.rs). Never splits a multibyte character.",
}

def extract_structs(content: str) -> List[Dict]:
    structs = []
    pattern = re.compile(r"struct\s+(\w+)\s*\{([^}]+)\}", re.DOTALL)
    for m in pattern.finditer(content):
        name = m.group(1)
        fields = []
        for line in m.group(2).splitlines():
            line = line.strip().rstrip(";")
            if line and not line.startswith(("//", "/*")):
                parts = line.split()
                if len(parts) >= 2:
                    fields.append({"type": " ".join(parts[:-1]), "name": parts[-1]})
        if fields:
            structs.append({"name": name, "fields": fields})
    return structs

def generate(content: str, source: str) -> str:
    structs = extract_structs(content)
    lines = [
        "// Generated by obs_cpp_to_rust_parser.py (work-smarter edition)",
        f"// Source: {source}",
        "// Patterns already solved in this crate — reuse them.",
        "",
    ]
    for s in structs:
        name = s["name"]
        hint = None
        for key, msg in KNOWN_PATTERNS.items():
            if key in name.lower() or key in source.lower():
                hint = msg
                break
        lines.append(f"// struct {name}")
        if hint:
            lines.append(f"// → {hint}")
        else:
            lines.append("// → Apply the same perfect pattern: safe core + C ABI shim + tests that prove the fix.")
        lines.append("")
    if not structs:
        lines.append("// No structs found. Check for known bugs (empty-string loops, mid-character cuts, uint8_t wraps).")
        lines.append("// Reuse the foundation modules in src/.")
    return "\n".join(lines)

def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    path = Path(sys.argv[1])
    content = path.read_text(errors="ignore")
    rust = generate(content, path.name)
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else path.with_suffix(".rs")
    out.write_text(rust)
    print(f"Wrote {out} — points at existing perfect patterns")

if __name__ == "__main__":
    main()
